$returned=(new App\CreditNoteService())->create(['invoice_id'=>$inter['id'],'note_date'=>$date,'reason'=>'Return goods','settlement'=>'Refund','items'=>[['invoice_item_id'=>$inter['items'][0]['id'],'quantity'=>'1']]],$owner);
