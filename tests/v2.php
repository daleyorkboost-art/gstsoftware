check(count($ledger->get((int)$account['id'])['transactions'])===3,'history contains original credit and separate clearances');
check($report->dashboard($range)['outstanding_credit']==='0.00' && $report->dashboard($range)['credit_sales']==='0.00','dashboard credit metrics update after clearance');
